"""
Turns the approved exercise illustrations (1254px PNGs, transparent) into
mobile-sized WebP files, keeping transparency and proportions:

  python3 -I scripts/optimize-exercise-images.py <folder with <category>/<slug>.png> [--out public/exercises/img]

For each <slug>.png it writes:
  <slug>.webp        800px square, for the "About this exercise" panel
  <slug>-thumb.webp  112px square, for exercise search results
Transparent margins are trimmed (ignoring faint edge haze), then the art is
centered on a square transparent canvas, so nothing is stretched. Writes
src/lib/exercise-images.ts with the slugs that have a picture.
"""
import os, sys
from PIL import Image

def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    if not args:
        sys.exit(__doc__)
    src = args[0]
    out = sys.argv[sys.argv.index("--out") + 1] if "--out" in sys.argv else "public/exercises/img"
    os.makedirs(out, exist_ok=True)
    slugs = []
    for root, _, files in os.walk(src):
        for f in sorted(files):
            if not f.endswith(".png"):
                continue
            slug = f[:-4]
            im = Image.open(os.path.join(root, f)).convert("RGBA")
            # Bounding box of clearly visible pixels (alpha > 24), plus a small margin.
            alpha = im.getchannel("A").point(lambda a: 255 if a > 24 else 0)
            box = alpha.getbbox() or (0, 0, *im.size)
            pad = round(max(im.size) * 0.03)
            box = (max(0, box[0] - pad), max(0, box[1] - pad), min(im.width, box[2] + pad), min(im.height, box[3] + pad))
            art = im.crop(box)
            side = max(art.size)
            square = Image.new("RGBA", (side, side), (0, 0, 0, 0))
            square.paste(art, ((side - art.width) // 2, (side - art.height) // 2))
            for name, size, quality in ((f"{slug}.webp", 800, 82), (f"{slug}-thumb.webp", 112, 80)):
                square.resize((size, size), Image.LANCZOS).save(os.path.join(out, name), "WEBP", quality=quality, method=6, exact=False)
            slugs.append(slug)
    slugs.sort()
    with open("src/lib/exercise-images.ts", "w") as fh:
        fh.write("// Generated by scripts/optimize-exercise-images.py. Exercises with an illustration\n")
        fh.write("// in public/exercises/img (<slug>.webp and <slug>-thumb.webp).\n")
        fh.write("export const EXERCISE_IMAGES: ReadonlySet<string> = new Set([\n")
        for s in slugs:
            fh.write(f'  "{s}",\n')
        fh.write("]);\n")
    print(f"{len(slugs)} illustrations written to {out}")

main()
