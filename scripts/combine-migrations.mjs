// Concatenates supabase/migrations/*.sql into supabase/combined.sql, for pasting
// into the Supabase SQL editor if you'd rather not use the CLI. Run once, on an empty project.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
const dir = "supabase/migrations";
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
const out = files.map((f) => `-- ===== ${f} =====\n${readFileSync(`${dir}/${f}`, "utf8")}`).join("\n\n");
writeFileSync("supabase/combined.sql", `-- Generated by scripts/combine-migrations.mjs. Do not edit; edit the migrations instead.\n\n${out}`);
console.log(`wrote supabase/combined.sql from ${files.length} migrations`);
